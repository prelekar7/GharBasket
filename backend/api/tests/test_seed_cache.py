"""The cached catalog seed of the fixtures writes what the real `seed_catalog` writes."""

import json
from typing import Any

import pytest
from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncSession

from gharbasket.tools.seed import seed_catalog as seed_catalog_for_real

from .seed_cache import TABLES, seed_catalog

pytestmark = [pytest.mark.anyio, pytest.mark.services]

VOLATILE = {"id", "created_at", "updated_at"}  # generated by the database on every run
NAMED_BY = ("categories", "products", "recipes")  # tables whose rows others point at by id


async def fingerprint(session: AsyncSession) -> dict[str, list[str]]:
    """Every catalog row without its generated ids and timestamps, rows pointing at others by the
    slug of the row they point at: equal after two seeds, though their uuids differ."""
    slugs: dict[str, str] = {}
    for table in NAMED_BY:
        for key, slug in (
            await session.execute(text(f"SELECT id, slug FROM catalog.{table}"))
        ).all():
            slugs[str(key)] = slug
    for key, valid_from in (
        await session.execute(text("SELECT id, valid_from FROM catalog.price_lists"))
    ).all():
        slugs[str(key)] = f"price-list-{valid_from}"
    found: dict[str, list[str]] = {}
    for table in TABLES:
        rows: list[dict[str, Any]] = (
            (await session.execute(text(f"SELECT to_jsonb(t) FROM catalog.{table} t")))
            .scalars()
            .all()
        )
        found[table] = sorted(
            json.dumps(
                {
                    key: slugs.get(str(value), value) if key.endswith("_id") else value
                    for key, value in row.items()
                    if key not in VOLATILE
                },
                sort_keys=True,
            )
            for row in rows
        )
    return found


async def test_the_cached_seed_writes_what_the_real_seed_writes(db_session: AsyncSession) -> None:
    async with db_session.begin_nested() as real_seed:
        saved = await seed_catalog_for_real(db_session)
        real = await fingerprint(db_session)
        await real_seed.rollback()
    first = await seed_catalog(db_session)  # builds the cache here, or restores it
    cached = await fingerprint(db_session)

    assert first == saved
    assert cached == real
    assert all(real[table] for table in TABLES)

    async with db_session.begin_nested() as again:  # a second, restoring call on an empty catalog
        await again.rollback()
    await db_session.execute(text("DELETE FROM catalog.recipes"))
    await db_session.execute(text("DELETE FROM catalog.festival_calendar"))
    await db_session.execute(text("DELETE FROM catalog.price_lists"))
    await db_session.execute(text("DELETE FROM catalog.products"))
    await db_session.execute(text("DELETE FROM catalog.categories"))
    assert await seed_catalog(db_session) == saved
    assert await fingerprint(db_session) == real


async def test_a_catalog_that_is_not_empty_gets_the_real_seed(db_session: AsyncSession) -> None:
    await seed_catalog(db_session)
    await db_session.execute(
        text("UPDATE catalog.products SET active = false WHERE slug = 'onion'")
    )
    await db_session.execute(text("DELETE FROM catalog.festival_calendar"))

    added = dict(await seed_catalog(db_session))

    assert added["onion"] is False  # still there, not created again
    festivals = (
        await db_session.execute(text("SELECT count(*) FROM catalog.festival_calendar"))
    ).scalar_one()
    assert festivals > 0  # the real seed adds what is missing
