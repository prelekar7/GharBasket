#!/usr/bin/env node
// Turns the tokens.json exported from "GharBasket · Design System" into src/tokens.css.
// Usage: pnpm --filter @gharbasket/ui sync-tokens <path/to/tokens.json> [design-system version id]
// Token changes are made in the design system first, then synced here (FRONTEND_DESIGN.md §13.6).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const [, , source, version = "unknown"] = process.argv;
if (!source) {
  console.error("Usage: sync-tokens <path/to/tokens.json> [version]");
  process.exit(1);
}

/** @typedef {{ name: string, value: string | Record<string, string> }} Token */
/** @type {{ color: { tokens: Token[] }, shadow: { tokens: Token[] }, type: { families: Record<string, string> }, [family: string]: any }} */
const tokens = JSON.parse(readFileSync(source, "utf8"));

/** Every token becomes --gb-<name>, so it never collides with Tailwind's own --color-* / --radius-* variables. */
const ref = (/** @type {string} */ value) => value.replace(/^\{(.+)\}$/, "var(--gb-$1)");
const light = [];
const dark = [];
for (const token of [...tokens.color.tokens, ...tokens.shadow.tokens]) {
  const { name, value } = token;
  if (typeof value === "string") {
    light.push(`  --gb-${name}: ${ref(value)};`);
  } else {
    light.push(`  --gb-${name}: ${ref(value.light)};`);
    if (value.dark) dark.push(`  --gb-${name}: ${ref(value.dark)};`);
  }
}
const fixed = ["spacing", "radius", "size", "duration", "easing"].flatMap((family) =>
  tokens[family].tokens.map((/** @type {Token} */ t) => `  --gb-${t.name}: ${t.value};`),
);
const fonts = Object.entries(tokens.type.families).map(
  ([key, stack]) => `  --gb-font-${key}: ${stack};`,
);

const css = `/* Generated by scripts/sync-tokens.js from GharBasket · Design System (version ${version}). Do not edit by hand. */
:root,
[data-theme="light"] {
${light.join("\n")}
${fixed.join("\n")}
${fonts.join("\n")}
}

[data-theme="dark"] {
${dark.join("\n")}
  color-scheme: dark;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${dark.map((line) => `  ${line}`).join("\n")}
    color-scheme: dark;
  }
}
`;

writeFileSync(fileURLToPath(new URL("../src/tokens.css", import.meta.url)), css);
console.log(
  `Wrote src/tokens.css: ${light.length} colour/shadow tokens, ${dark.length} dark overrides.`,
);
