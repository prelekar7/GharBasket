import { ApiProblem } from "@/lib/api.js";
import { formatDate, rupees } from "@/lib/fleet.js";
import { getPartner } from "../data.js";

/** @param {string} s */
const esc = (s) => s.replace(/[&<>"']/g, (c) => `&#${c.charCodeAt(0)};`);

/**
 * A printable income certificate built from the partner's payouts (the ledger's weekly earnings). The browser's
 * print dialog saves it as a PDF; the API's own signed PDF replaces this when M8 provides it.
 * @param {Request} _request
 * @param {{ params: Promise<{ id: string }> }} ctx
 */
export async function GET(_request, { params }) {
  const { id } = await params;
  try {
    const p = await getPartner(id);
    const total = p.payouts.items.reduce((sum, w) => sum + w.paid_paise, 0);
    const rows = p.payouts.items
      .map(
        (w) =>
          `<tr><td>Week of ${esc(w.week)}</td><td class="n">${w.units}</td><td class="n">${esc(rupees(w.paid_paise))}</td></tr>`,
      )
      .join("");
    const html = `<!doctype html><html lang="en-IN"><meta charset="utf-8"><title>Income certificate · ${esc(p.name)}</title>
<style>body{font:16px/1.5 system-ui,sans-serif;max-width:640px;margin:48px auto;padding:0 24px;color:#1e1b16}h1{font-size:28px;margin:0 0 4px}
table{border-collapse:collapse;width:100%;margin:24px 0}th,td{padding:8px 4px;border-bottom:1px solid #ccc;text-align:left}.n{text-align:right}
.muted{color:#4a4339;font-size:14px}</style>
<h1>Income certificate</h1><p class="muted">GharBasket · ${esc(p.hub.name)} · issued ${esc(formatDate(new Date().toISOString()))}</p>
<p>This certifies that <strong>${esc(p.name)}</strong> works with GharBasket as a ${esc(p.kind_label.toLowerCase())} at ${esc(p.hub.name)} and was paid as follows.</p>
<table><thead><tr><th>Period</th><th class="n">${esc(p.payouts.unit_label)}</th><th class="n">Paid</th></tr></thead><tbody>${rows}</tbody>
<tfoot><tr><th>Total</th><th></th><th class="n">${esc(rupees(total))}</th></tr></tfoot></table>
<p class="muted">Amounts come from the GharBasket ledger. This copy is generated by the console.</p>
<script>window.print()</script></html>`;
    return new Response(html, {
      headers: { "content-type": "text/html; charset=utf-8", "cache-control": "no-store" },
    });
  } catch (e) {
    if (e instanceof ApiProblem && e.status === 404)
      return new Response("Partner not found", { status: 404 });
    return new Response("Could not prepare the certificate. Try again.", { status: 500 });
  }
}
