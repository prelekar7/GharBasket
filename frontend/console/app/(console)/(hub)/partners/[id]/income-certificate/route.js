import { ApiProblem } from "@/lib/api.js";
import { formatDate, rupees } from "@/lib/fleet.js";
import { KIND_LABEL } from "@/lib/partners.js";
import { weekRange } from "@/lib/payout-weeks.js";
import { getPartner } from "../data.js";

/** @param {string} s */
const esc = (s) => s.replace(/[&<>"']/g, (c) => `&#${c.charCodeAt(0)};`);

/**
 * A printable income certificate built from the partner's paid weekly payouts (the ledger's earnings). The browser's
 * print dialog saves it as a PDF; the API's own PDF (`GET /v1/earnings/certificate`, M8 §3.7, for the partner herself)
 * replaces this when it ships.
 * @param {Request} _request
 * @param {{ params: Promise<{ id: string }> }} ctx
 */
export async function GET(_request, { params }) {
  const { id } = await params;
  try {
    const { partner: p, hubName, payouts } = await getPartner(id);
    const name = p.name ?? p.display_name;
    const paid = payouts.filter((w) => w.status === "processed");
    const total = paid.reduce((sum, w) => sum + w.amount_paise, 0);
    const rows = paid
      .map(
        (w) =>
          `<tr><td>${esc(weekRange(w.period))} (${esc(w.week)})</td><td class="n">${esc(rupees(w.amount_paise))}</td></tr>`,
      )
      .join("");
    const html = `<!doctype html><html lang="en-IN"><meta charset="utf-8"><title>Income certificate · ${esc(name)}</title>
<style>body{font:16px/1.5 system-ui,sans-serif;max-width:640px;margin:48px auto;padding:0 24px;color:#1e1b16}h1{font-size:28px;margin:0 0 4px}
table{border-collapse:collapse;width:100%;margin:24px 0}th,td{padding:8px 4px;border-bottom:1px solid #ccc;text-align:left}.n{text-align:right}
.muted{color:#4a4339;font-size:14px}</style>
<h1>Income certificate</h1><p class="muted">GharBasket · ${esc(hubName)} · issued ${esc(formatDate(new Date().toISOString()))}</p>
<p>This certifies that <strong>${esc(name)}</strong> works with GharBasket as a ${esc(KIND_LABEL[p.kind].toLowerCase())} at ${esc(hubName)} and was paid as follows.</p>
<table><thead><tr><th>Period</th><th class="n">Paid</th></tr></thead><tbody>${rows}</tbody>
<tfoot><tr><th>Total</th><th class="n">${esc(rupees(total))}</th></tr></tfoot></table>
<p class="muted">Amounts come from the GharBasket ledger. This copy is generated by the console.</p>
<script>window.print()</script></html>`;
    return new Response(html, {
      headers: { "content-type": "text/html; charset=utf-8", "cache-control": "no-store" },
    });
  } catch (e) {
    if (e instanceof ApiProblem && e.status === 404)
      return new Response("Partner not found", { status: 404 });
    return new Response("Could not prepare the certificate. Try again.", { status: 500 });
  }
}
